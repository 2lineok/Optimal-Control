vtkfile = 'your_mesh_file.vtk';  % <-- Specify your .vtk mesh file here
[coords, faces] = read_vtk_ascii(vtkfile);
N = size(coords,1);
% NOTE:
%   Replace the paths below with your own observation .txt files.
%   Each file name includes a timestamp in the format YYYYMMDDHHMMSS,
%   which can be converted to datetime for temporal ordering.
obs_files = {
    'your_observation_file_1.txt'
    'your_observation_file_2.txt'
    'your_observation_file_3.txt'
    'your_observation_file_4.txt'
    'your_observation_file_5.txt'
};

% NOTE:
%   This file should be generated by running Main.m.
%   Please replace 'your_file.mat' with the actual output file name
%   produced by Main.m before running this script.
%   Default name will be 'filename = sprintf('data_alpha%s_ts%s.mat', alpha_str, tsu_str)'

loadFile = 'your_file.mat';
load(loadFile)



Uobs = cell(numel(obs_files),1);
for k = 1:numel(obs_files)
    if ~isfile(obs_files{k})
        error('Missing file: %s', obs_files{k});
    end
    % If first row is text, readmatrix will skip it.
    u = readmatrix(obs_files{k});  
    if numel(u) ~= N
        error('Size mismatch in %s', obs_files{k});
    end
    Uobs{k} = u(:);
end


u_stack = cat(2, Uobs{:});
u_max = max(u_stack, [], 'all');
if u_max == 0, error('All-zero observations'); end
for k=1:numel(Uobs)
    Uobs{k} = Uobs{k} / u_max;
end
u0 = Uobs{1};


Dfunc = @(x,y,z) 1.0; 
[K0, M, ~] = assemble_surfaceFEM_fast(coords, faces, Dfunc); % K for D=1


substeps_per_year = 30;
Tfinal = 8;
maxit = 100;
dt = 1 / substeps_per_year; 

Nsteps = round(Tfinal * substeps_per_year);










K = D * K0;

A = M + dt*K;    % sparse SPD matrix
% incomplete Cholesky factorization (drop tolerance can be modified)
L = ichol(A, struct('type','ict','droptol',1e-4));

[Usim_opt, tgrid] = Solve_u(u0, K, M, rho, C_time_or_fun, dt,A,L);
[Wsim_opt, ~] = Solve_w(Usim_opt, M, K, rho, C_time_or_fun, dt,A,L);
C_avg = (trapz(tgrid, C_time_or_fun) / Tfinal) * ones(Nsteps+1,1);

[Usim, tgrid] = Solve_u(u0, K, M, rho, C_avg, dt,A,L);
[Wsim, ~] = Solve_w(Usim, M, K, rho, C_avg, dt,A,L);










tvals = [1 3 5 7];


Usim_int     = cumtrapz(tgrid, Usim, 2);
Usim_opt_int = cumtrapz(tgrid, Usim_opt, 2);
U_int_domain_t=((M*ones(N,1)).')*Usim_int;
U_int_domain_opt_t=((M*ones(N,1)).')*Usim_opt_int;
U_int_domain=((M*ones(N,1)).')*Usim;
U_int_domain_opt=((M*ones(N,1)).')*Usim_opt;


cmin = min([Usim_opt_int(:)]);
cmax = max([Usim_int(:)]);

figure;
for k = 1:length(tvals)
    [~, tidx] = min(abs(tgrid - tvals(k)));

    % --- Constant control ---
    subplot(2, length(tvals), k);
    trisurf(faces, coords(:,1), coords(:,2), coords(:,3), Usim_int(:,tidx));
    shading interp; axis equal off;
    caxis([cmin cmax]);
    title(sprintf('$\\int_0^t U(x,s) ds$ at $t = %.1f$', tgrid(tidx)), 'Interpreter','latex');


    % --- Optimal control ---
    subplot(2, length(tvals), length(tvals)+k);
    trisurf(faces, coords(:,1), coords(:,2), coords(:,3), Usim_opt_int(:,tidx));
    shading interp; axis equal off;
    caxis([cmin cmax]);
    
    title(sprintf('$\\int_0^t U^*(x,s) ds$ at $t = %.1f$', tgrid(tidx)), 'Interpreter','latex');

end


